-- Rodada vigente, ou a última se o campeonato já acabou
create function public.rodada_atual() returns public.rodadas
language sql stable security invoker set search_path = '' as $$
  select r.* from public.rodadas r
  where r.inicio <= (now() at time zone 'America/Sao_Paulo')::date
  order by r.numero desc limit 1;
$$;

-- O morador do distrito informa que o problema foi resolvido. Isso ainda não vale gol.
create function public.marcar_resolvido(p_chamado bigint) returns text
language plpgsql security definer set search_path = '' as $$
declare
  v_uid uuid := auth.uid();
  v_chamado public.chamados;
begin
  if v_uid is null then raise exception 'Entre na sua conta para continuar.'; end if;
  select * into v_chamado from public.chamados where id = p_chamado for update;
  if not found then raise exception 'Chamado não encontrado.'; end if;
  if v_chamado.status <> 'aberto' then raise exception 'Só um chamado aberto pode ser marcado como resolvido.'; end if;
  if not exists (select 1 from public.perfis p where p.id = v_uid and p.distrito_id = v_chamado.distrito_id) then
    raise exception 'Só moradores deste distrito podem fazer isso.';
  end if;
  update public.chamados set status = 'resolvido', resolvido_em = now(), resolvido_por = v_uid where id = p_chamado;
  return 'resolvido';
end;
$$;

-- O VAR: 2 confirmações geram o gol, e 2 contestações reabrem o chamado.
create function public.votar_var(p_chamado bigint, p_resultado text, p_foto_path text) returns text
language plpgsql security definer set search_path = '' as $$
declare
  v_uid uuid := auth.uid();
  v_chamado public.chamados;
  v_confirma int;
  v_contesta int;
begin
  if v_uid is null then raise exception 'Entre na sua conta para continuar.'; end if;
  if p_resultado not in ('confirma', 'contesta') then raise exception 'Voto inválido.'; end if;
  select * into v_chamado from public.chamados where id = p_chamado for update;
  if not found then raise exception 'Chamado não encontrado.'; end if;
  if v_chamado.status <> 'resolvido' then raise exception 'Este chamado não está aguardando o VAR.'; end if;
  if not exists (select 1 from public.perfis p where p.id = v_uid and p.distrito_id = v_chamado.distrito_id) then
    raise exception 'Só vizinhos deste distrito podem votar.';
  end if;
  if v_uid = v_chamado.autor_id or v_uid = v_chamado.resolvido_por then
    raise exception 'Quem relatou ou marcou como resolvido não pode votar neste chamado.';
  end if;
  if not exists (
    select 1 from storage.objects o
    where o.bucket_id = 'fotos' and o.name = p_foto_path and o.owner_id = v_uid::text
  ) then
    raise exception 'A foto do VAR é obrigatória.';
  end if;

  insert into public.confirmacoes (chamado_id, morador_id, resultado, foto_path)
  values (p_chamado, v_uid, p_resultado, p_foto_path)
  on conflict (chamado_id, morador_id) do nothing;
  if not found then raise exception 'Você já votou neste chamado.'; end if;

  select count(*) filter (where resultado = 'confirma'), count(*) filter (where resultado = 'contesta')
    into v_confirma, v_contesta
    from public.confirmacoes where chamado_id = p_chamado;

  if v_confirma >= 2 and v_confirma > v_contesta then
    update public.chamados set status = 'validado', validado_em = now() where id = p_chamado;
    insert into public.gols (chamado_id, rodada_id, distrito_id, valor)
    select p_chamado, (public.rodada_atual()).id, v_chamado.distrito_id, s.gols
      from public.servicos s where s.id = v_chamado.servico_id;
    return 'gol';
  end if;

  if v_contesta >= 2 then
    delete from public.confirmacoes where chamado_id = p_chamado;
    update public.chamados set status = 'aberto', resolvido_em = null, resolvido_por = null where id = p_chamado;
    return 'anulado';
  end if;

  return 'aguardando';
end;
$$;

create function public.cancelar_chamado(p_chamado bigint) returns text
language plpgsql security definer set search_path = '' as $$
begin
  update public.chamados set status = 'cancelado'
   where id = p_chamado and autor_id = auth.uid() and status = 'aberto';
  if not found then raise exception 'Só o autor pode cancelar um chamado aberto.'; end if;
  return 'cancelado';
end;
$$;

-- Dados agregados e sem referência de local, liberados também na página de vendas
create function public.placar_partidas(p_rodada smallint default null)
returns table (
  partida_id bigint, rodada_numero smallint, inicio date, fim date,
  casa_id smallint, casa text, gols_casa bigint,
  fora_id smallint, fora text, gols_fora bigint
)
language sql stable security definer set search_path = '' as $$
  select p.id, r.numero, r.inicio, r.fim,
         p.casa_id, dc.nome,
         coalesce((select sum(g.valor) from public.gols g where g.rodada_id = p.rodada_id and g.distrito_id = p.casa_id), 0)::bigint,
         p.fora_id, df.nome,
         coalesce((select sum(g.valor) from public.gols g where g.rodada_id = p.rodada_id and g.distrito_id = p.fora_id), 0)::bigint
    from public.partidas p
    join public.rodadas r on r.id = p.rodada_id
    join public.distritos dc on dc.id = p.casa_id
    join public.distritos df on df.id = p.fora_id
   where p.rodada_id = coalesce(p_rodada, (public.rodada_atual()).id)
   order by dc.zona, dc.nome;
$$;

create function public.classificacao()
returns table (
  distrito_id smallint, nome text, zona text, jogos bigint, vitorias bigint, empates bigint,
  derrotas bigint, gols_pro bigint, pontos bigint
)
language sql stable security definer set search_path = '' as $$
  with placar as (
    select p.casa_id as time_id,
           coalesce((select sum(g.valor) from public.gols g where g.rodada_id = p.rodada_id and g.distrito_id = p.casa_id), 0) as pro,
           coalesce((select sum(g.valor) from public.gols g where g.rodada_id = p.rodada_id and g.distrito_id = p.fora_id), 0) as contra
      from public.partidas p join public.rodadas r on r.id = p.rodada_id
     where r.fim < (now() at time zone 'America/Sao_Paulo')::date
    union all
    select p.fora_id,
           coalesce((select sum(g.valor) from public.gols g where g.rodada_id = p.rodada_id and g.distrito_id = p.fora_id), 0),
           coalesce((select sum(g.valor) from public.gols g where g.rodada_id = p.rodada_id and g.distrito_id = p.casa_id), 0)
      from public.partidas p join public.rodadas r on r.id = p.rodada_id
     where r.fim < (now() at time zone 'America/Sao_Paulo')::date
  )
  select d.id, d.nome, d.zona,
         count(pl.time_id),
         count(*) filter (where pl.pro > pl.contra),
         count(*) filter (where pl.pro = pl.contra),
         count(*) filter (where pl.pro < pl.contra),
         coalesce((select sum(g.valor) from public.gols g where g.distrito_id = d.id), 0)::bigint,
         (3 * count(*) filter (where pl.pro > pl.contra) + count(*) filter (where pl.pro = pl.contra))
    from public.distritos d
    left join placar pl on pl.time_id = d.id
   group by d.id, d.nome, d.zona
   order by 9 desc, 8 desc, d.nome;
$$;

create function public.ultimos_gols(p_limite int default 6)
returns table (distrito text, servico text, valor smallint, criado_em timestamptz, demo boolean)
language sql stable security definer set search_path = '' as $$
  select d.nome, s.nome, g.valor, g.criado_em, c.demo
    from public.gols g
    join public.chamados c on c.id = g.chamado_id
    join public.servicos s on s.id = c.servico_id
    join public.distritos d on d.id = g.distrito_id
   order by g.criado_em desc
   limit least(p_limite, 20);
$$;

