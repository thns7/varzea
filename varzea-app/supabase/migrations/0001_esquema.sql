-- Várzea: esquema, regras do jogo e segurança
create table public.distritos (
  id smallint generated by default as identity primary key,
  nome text not null unique,
  zona text not null check (zona in ('Centro', 'Norte', 'Sul', 'Leste', 'Oeste'))
);

create table public.categorias (
  id smallint generated by default as identity primary key,
  nome text not null unique
);

create table public.servicos (
  id smallint generated by default as identity primary key,
  categoria_id smallint not null references public.categorias (id),
  nome text not null unique,
  gols smallint not null check (gols >= 1),
  chance_30d numeric(4, 3) not null check (chance_30d between 0 and 1)
);

create table public.perfis (
  id uuid primary key references auth.users (id) on delete cascade,
  nome text not null check (char_length(trim(nome)) between 2 and 60),
  distrito_id smallint not null references public.distritos (id),
  criado_em timestamptz not null default now()
);

create table public.rodadas (
  id smallint generated by default as identity primary key,
  numero smallint not null unique,
  inicio date not null,
  fim date not null,
  check (fim >= inicio)
);

create table public.partidas (
  id bigint generated by default as identity primary key,
  rodada_id smallint not null references public.rodadas (id),
  casa_id smallint not null references public.distritos (id),
  fora_id smallint not null references public.distritos (id),
  check (casa_id <> fora_id),
  unique (rodada_id, casa_id),
  unique (rodada_id, fora_id)
);

create table public.chamados (
  id bigint generated by default as identity primary key,
  servico_id smallint not null references public.servicos (id),
  distrito_id smallint not null references public.distritos (id),
  autor_id uuid references public.perfis (id) on delete set null,
  referencia text not null check (char_length(trim(referencia)) between 5 and 120),
  foto_path text check (char_length(foto_path) <= 200),
  status text not null default 'aberto' check (status in ('aberto', 'resolvido', 'validado', 'cancelado')),
  demo boolean not null default false,
  criado_em timestamptz not null default now(),
  resolvido_em timestamptz,
  resolvido_por uuid references public.perfis (id) on delete set null,
  validado_em timestamptz,
  check (status not in ('resolvido', 'validado') or resolvido_em is not null)
);

create table public.confirmacoes (
  id bigint generated by default as identity primary key,
  chamado_id bigint not null references public.chamados (id) on delete cascade,
  morador_id uuid not null references public.perfis (id) on delete cascade,
  resultado text not null check (resultado in ('confirma', 'contesta')),
  foto_path text not null check (char_length(foto_path) <= 200),
  criado_em timestamptz not null default now(),
  unique (chamado_id, morador_id)
);

create table public.gols (
  id bigint generated by default as identity primary key,
  chamado_id bigint not null unique references public.chamados (id) on delete cascade,
  rodada_id smallint not null references public.rodadas (id),
  distrito_id smallint not null references public.distritos (id),
  valor smallint not null check (valor >= 1),
  criado_em timestamptz not null default now()
);

create table public.interessados (
  id bigint generated by default as identity primary key,
  nome text not null check (char_length(trim(nome)) between 2 and 80),
  email text not null check (char_length(email) <= 160 and email ~* '^[^@\s]+@[^@\s]+\.[^@\s]+$'),
  tipo text not null check (tipo in ('comercio', 'prefeitura', 'associacao', 'outro')),
  mensagem text check (char_length(mensagem) <= 500),
  consentiu boolean not null check (consentiu),
  criado_em timestamptz not null default now()
);

create index on public.servicos (categoria_id);
create index on public.perfis (distrito_id);
create index on public.partidas (casa_id);
create index on public.partidas (fora_id);
create index on public.chamados (servico_id);
create index on public.chamados (distrito_id, status);
